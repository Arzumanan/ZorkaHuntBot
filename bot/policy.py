def policy_payload(operator: str | None = None, contact: str | None = None) -> dict:
    operator = (operator or "").strip() or DEFAULT_OPERATOR
    contact = (contact or "").strip() or DEFAULT_CONTACT
    return {
        "version": POLICY_VERSION,
        "date": POLICY_DATE,
        "title": TITLE,
        "operator": operator,
        "contact": contact,
        "summary": CONSENT_SUMMARY,
        "checkbox": CONSENT_CHECKBOX,
        "sections": _sections(operator, contact),
    }


def render_policy_html(payload: dict) -> str:
    """Самостоятельная страница /privacy: открывается и без Telegram, без JavaScript."""
    e = html.escape
    parts = [f"<h1>{e(payload['title'])}</h1>", f"<p class=\"muted\">Версия {e(payload['version'])} от {e(payload['date'])}</p>"]
    for sec in payload["sections"]:
        parts.append(f"<h2>{e(sec['title'])}</h2>")
        parts += [f"<p>{e(p)}</p>" for p in sec.get("paragraphs", [])]
        if sec.get("items"):
            parts.append("<ul>" + "".join(f"<li>{e(i)}</li>" for i in sec["items"]) + "</ul>")
        parts += [f"<p>{e(p)}</p>" for p in sec.get("after", [])]
    return (
        "<!DOCTYPE html><html lang=\"ru\"><head><meta charset=\"utf-8\">"
        "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">"
        f"<title>{e(payload['title'])}</title>"
        "<style>body{font:16px/1.5 -apple-system,Segoe UI,Roboto,sans-serif;max-width:720px;margin:0 auto;padding:16px;color:#1c1c1e}"
        "h1{font-size:22px}h2{font-size:17px;margin-top:22px}.muted{color:#8a8a8e}"
        "@media(prefers-color-scheme:dark){body{background:#1c1c1e;color:#f2f2f7}}</style></head><body>"
        + "".join(parts) + "</body></html>"
    )
